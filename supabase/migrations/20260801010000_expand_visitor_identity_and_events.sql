create or replace function public.get_admin_customer_overview()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_today_start timestamptz :=
    (date_trunc('day', now() at time zone 'Asia/Seoul') at time zone 'Asia/Seoul');
  v_registered_customers bigint;
  v_today_visitors bigint;
  v_active_now bigint;
  v_repeat_visitors bigint;
  v_confirmed_today bigint;
  v_lead_today bigint;
  v_anonymous_today bigint;
begin
  if auth.uid() is null or not public.is_admin(auth.uid()) then
    raise exception '관리자 권한이 필요합니다.';
  end if;

  select count(*)
  into v_registered_customers
  from auth.users auth_user
  where not public.is_admin(auth_user.id);

  select count(distinct visitor_id)
  into v_today_visitors
  from public.site_visit_sessions
  where last_seen_at >= v_today_start;

  select count(distinct visitor_id)
  into v_active_now
  from public.site_visit_sessions
  where last_seen_at >= now() - interval '5 minutes';

  select count(*)
  into v_repeat_visitors
  from (
    select visitor_id
    from public.site_visit_sessions
    group by visitor_id
    having count(*) >= 2
  ) repeated;

  select count(distinct visitor_id)
  into v_confirmed_today
  from public.site_visit_sessions
  where last_seen_at >= v_today_start
    and user_id is not null;

  select count(distinct visitor_id)
  into v_lead_today
  from public.site_visit_sessions
  where last_seen_at >= v_today_start
    and user_id is null
    and lead_code is not null;

  select count(distinct visitor_id)
  into v_anonymous_today
  from public.site_visit_sessions
  where last_seen_at >= v_today_start
    and user_id is null
    and lead_code is null;

  return jsonb_build_object(
    'registered_customers', v_registered_customers,
    'today_visitors', v_today_visitors,
    'active_now', v_active_now,
    'repeat_visitors', v_repeat_visitors,
    'confirmed_today', v_confirmed_today,
    'lead_today', v_lead_today,
    'anonymous_today', v_anonymous_today
  );
end;
$$;

