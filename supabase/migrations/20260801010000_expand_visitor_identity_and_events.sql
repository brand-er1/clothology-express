create or replace function public.get_admin_visit_sessions(
  p_limit integer default 300,
  p_period text default 'today'
)
returns table (
  session_id uuid,
  visitor_id uuid,
  user_id uuid,
  email text,
  display_name text,
  account_type text,
  identity_status text,
  lead_code text,
  lead_name text,
  lead_channel text,
  started_at timestamptz,
  last_seen_at timestamptz,
  entry_path text,
  last_path text,
  referrer text,
  utm_source text,
  utm_medium text,
  utm_campaign text,
  utm_content text,
  device_type text,
  browser text,
  page_view_count integer,
  event_count bigint,
  last_event_name text,
  journey jsonb,
  is_active boolean
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_start timestamptz;
begin
  if auth.uid() is null or not public.is_admin(auth.uid()) then
    raise exception '관리자 권한이 필요합니다.';
  end if;

  v_start := case p_period
    when 'today' then
      (date_trunc('day', now() at time zone 'Asia/Seoul') at time zone 'Asia/Seoul')
    when '7d' then now() - interval '7 days'
    else null
  end;

  return query
  select
    visit.session_id,
    visit.visitor_id,
    visit.user_id,
    auth_user.email::text,
    coalesce(
      nullif(profile.brand_name, ''),
      nullif(profile.username, ''),
      nullif(profile.full_name, ''),
      auth_user.email::text,
      nullif(visit.lead_name, ''),
      '익명 방문자 #' || upper(left(visit.visitor_id::text, 4))
    ) as display_name,
    profile.account_type,
    case
      when visit.user_id is not null then 'confirmed'
      when visit.lead_code is not null then 'lead'
      else 'anonymous'
    end as identity_status,
    visit.lead_code,
    visit.lead_name,
    visit.lead_channel,
    visit.started_at,
    visit.last_seen_at,
    visit.entry_path,
    visit.last_path,
    visit.referrer,
    visit.utm_source,
    visit.utm_medium,
    visit.utm_campaign,
    visit.utm_content,
    visit.device_type,
    visit.browser,
    visit.page_view_count,
    coalesce(event_total.event_count, 0),
    coalesce(event_total.last_event_name, visit.last_event_name),
    coalesce(event_journey.journey, '[]'::jsonb),
    visit.last_seen_at >= now() - interval '5 minutes' as is_active
  from public.site_visit_sessions visit
  left join auth.users auth_user on auth_user.id = visit.user_id
  left join public.profiles profile on profile.id = visit.user_id
  left join lateral (
    select
      count(*)::bigint as event_count,
      (array_agg(event.event_name order by event.created_at desc))[1] as last_event_name
    from public.site_visit_events event
    where event.session_id = visit.session_id
  ) event_total on true
  left join lateral (
    select jsonb_agg(
      jsonb_build_object(
        'event_name', recent.event_name,
        'path', recent.path,
        'metadata', recent.metadata,
        'created_at', recent.created_at
      ) order by recent.created_at asc
    ) as journey
    from (
      select event.event_name, event.path, event.metadata, event.created_at
      from public.site_visit_events event
      where event.session_id = visit.session_id
      order by event.created_at desc
      limit 20
    ) recent
  ) event_journey on true
  where v_start is null or visit.last_seen_at >= v_start
  order by visit.last_seen_at desc
  limit least(greatest(coalesce(p_limit, 300), 1), 1000);
end;
$$;

revoke all on function public.get_admin_visit_sessions(integer, text) from public;
grant execute on function public.get_admin_visit_sessions(integer, text)
