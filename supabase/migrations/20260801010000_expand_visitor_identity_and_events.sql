create or replace function public.track_site_visit(
  p_session_id uuid,
  p_visitor_id uuid,
  p_path text,
  p_referrer text default null,
  p_device_type text default 'unknown',
  p_browser text default 'unknown',
  p_is_page_view boolean default true,
  p_lead_code text default null,
  p_utm_source text default null,
  p_utm_medium text default null,
  p_utm_campaign text default null,
  p_utm_content text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_path text := left(coalesce(nullif(trim(p_path), ''), '/'), 300);
  v_referrer text := nullif(left(trim(coalesce(p_referrer, '')), 500), '');
  v_device_type text := case
    when p_device_type in ('desktop', 'mobile', 'tablet') then p_device_type
    else 'unknown'
  end;
  v_browser text := left(coalesce(nullif(trim(p_browser), ''), 'unknown'), 50);
  v_lead_code text := nullif(left(trim(coalesce(p_lead_code, '')), 64), '');
  v_lead_name text;
  v_lead_channel text;
  v_utm_source text := nullif(left(trim(coalesce(p_utm_source, '')), 100), '');
  v_utm_medium text := nullif(left(trim(coalesce(p_utm_medium, '')), 100), '');
  v_utm_campaign text := nullif(left(trim(coalesce(p_utm_campaign, '')), 150), '');
  v_utm_content text := nullif(left(trim(coalesce(p_utm_content, '')), 150), '');
  v_is_new_session boolean;
begin
  if p_session_id is null or p_visitor_id is null then
    return;
  end if;

  if v_user_id is not null and public.is_admin(v_user_id) then
    delete from public.site_visit_sessions
    where visitor_id = p_visitor_id
      and user_id is null;
    return;
  end if;

  if v_lead_code is not null then
    select tracking.lead_name, tracking.channel
    into v_lead_name, v_lead_channel
    from public.sales_tracking_links tracking
    where tracking.lead_code = v_lead_code
      and tracking.is_active
    limit 1;

    if v_lead_name is null then
      v_lead_code := null;
    end if;
  end if;

  select not exists (
    select 1
    from public.site_visit_sessions existing
    where existing.session_id = p_session_id
  ) into v_is_new_session;

  insert into public.site_visit_sessions (
    session_id,
    visitor_id,
    user_id,
    entry_path,
    last_path,
    referrer,
    device_type,
    browser,
    page_view_count,
    lead_code,
    lead_name,
    lead_channel,
    utm_source,
    utm_medium,
    utm_campaign,
    utm_content,
    last_event_name
  ) values (
    p_session_id,
    p_visitor_id,
    v_user_id,
    v_path,
    v_path,
    v_referrer,
    v_device_type,
    v_browser,
    case when coalesce(p_is_page_view, true) then 1 else 0 end,
    v_lead_code,
    v_lead_name,
    v_lead_channel,
    v_utm_source,
    v_utm_medium,
    v_utm_campaign,
    v_utm_content,
    case when coalesce(p_is_page_view, true) then 'page_view' else null end
  )
  on conflict (session_id) do update
  set
    user_id = coalesce(v_user_id, site_visit_sessions.user_id),
    last_seen_at = now(),
    last_path = v_path,
    device_type = v_device_type,
    browser = v_browser,
    page_view_count = site_visit_sessions.page_view_count
      + case when coalesce(p_is_page_view, true) then 1 else 0 end,
    lead_code = coalesce(v_lead_code, site_visit_sessions.lead_code),
    lead_name = coalesce(v_lead_name, site_visit_sessions.lead_name),
    lead_channel = coalesce(v_lead_channel, site_visit_sessions.lead_channel),
    utm_source = coalesce(site_visit_sessions.utm_source, v_utm_source),
    utm_medium = coalesce(site_visit_sessions.utm_medium, v_utm_medium),
    utm_campaign = coalesce(site_visit_sessions.utm_campaign, v_utm_campaign),
    utm_content = coalesce(site_visit_sessions.utm_content, v_utm_content),
    last_event_name = case
      when coalesce(p_is_page_view, true) then 'page_view'
      else site_visit_sessions.last_event_name
    end;

  if v_user_id is not null then
    update public.site_visit_sessions
    set user_id = v_user_id
    where visitor_id = p_visitor_id
      and user_id is null;

    update public.site_visit_events
    set user_id = v_user_id
    where visitor_id = p_visitor_id
      and user_id is null;
  end if;

  if v_is_new_session and v_lead_code is not null then
    update public.sales_tracking_links
    set
      click_count = click_count + 1,
      last_clicked_at = now()
    where lead_code = v_lead_code;
  end if;

  if coalesce(p_is_page_view, true) then
    insert into public.site_visit_events (
      session_id,
      visitor_id,
      user_id,
      event_name,
      path,
      metadata
    ) values (
      p_session_id,
      p_visitor_id,
      v_user_id,
      'page_view',
      v_path,
      jsonb_strip_nulls(jsonb_build_object(
        'utm_source', v_utm_source,
        'utm_medium', v_utm_medium,
        'utm_campaign', v_utm_campaign
      ))
    );
  end if;

  if v_is_new_session and random() < 0.02 then
    delete from public.site_visit_sessions
    where last_seen_at < now() - interval '180 days';
  end if;
end;
$$;

